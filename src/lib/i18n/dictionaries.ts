/**
 * `as const` above makes every value a string *literal* type, which is what
 * lets the keys be checked — but a literal type would also demand that `pt`
 * repeat the English text verbatim. Widen the leaves back to `string` while
 * keeping the object shape exact.
 */
type Widen<T> = T extends readonly (infer U)[]
  ? readonly Widen<U>[]
  : T extends string
    ? string
    : T extends object
      ? { -readonly [K in keyof T]: Widen<T[K]> }
      : T;

